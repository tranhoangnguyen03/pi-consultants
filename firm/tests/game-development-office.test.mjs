import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildOffice,loadFirm} from '../scripts/factory.mjs';
import {inspect} from '../skills/game/game-dev-routing/scripts/inspect-project.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
test('H builds independent practice, shared runtime and case boundary',async t=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'hq-game-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 const {offices,toolset}=await loadFirm(root);const h=offices.find(x=>x.role==='game');
 assert(h);assert.equal(h.letter,'H');assert.equal(new Set(offices.map(x=>x.letter)).size,offices.length);
 const hq=await buildOffice(root,h,toolset,path.join(dir,h.folder));
 const settings=JSON.parse(await fs.readFile(path.join(hq,'.pi/settings.json'),'utf8'));
 const config=JSON.parse(await fs.readFile(path.join(hq,'.pi/hq.json'),'utf8'));
 assert.equal(config.role,'game');assert.equal(config.stateDir,'../.hq');
 assert.deepEqual(settings.packages,toolset.packages);
 const skills=(await fs.readdir(path.join(hq,'.pi/skills'))).sort();
 assert.deepEqual(skills,[...await fs.readdir(path.join(root,'skills/shared')),...await fs.readdir(path.join(root,'skills/game'))].sort());
 assert(!skills.includes('design-direction'));assert(!skills.includes('last30days'));
 assert.match(await fs.readFile(path.join(hq,'AGENTS.md'),'utf8'),/consultant H, the game development consultant/);
 assert.match(await fs.readFile(path.join(hq,'AGENTS.md'),'utf8'),/Consultation is the entry point/);
 const marker=JSON.parse(await fs.readFile(path.join(hq,'HQ-ROLE.json'),'utf8'));
 assert.equal(marker.role,'game');assert(Object.keys(marker.generated).some(x=>x.endsWith('/inspect-project.mjs')));
});
test('H reads engine evidence without choosing one in ambiguous projects',async t=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'game-inspect-'));t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 assert.equal((await inspect(dir)).status,'unknown');
 await fs.writeFile(path.join(dir,'project.godot'),'config/features=PackedStringArray("4.7", "GL Compatibility")\n');
 assert.deepEqual((await inspect(dir)).matches.map(x=>[x.engine,x.version]),[['godot','4.7']]);
 await fs.mkdir(path.join(dir,'Assets'));await fs.mkdir(path.join(dir,'ProjectSettings'));
 await fs.writeFile(path.join(dir,'ProjectSettings/ProjectVersion.txt'),'m_EditorVersion: 6000.3.27f1\n');
 assert.equal((await inspect(dir)).status,'ambiguous');
 await fs.rm(path.join(dir,'project.godot'));
 assert.deepEqual((await inspect(dir)).matches.map(x=>[x.engine,x.version]),[['unity','6000.3.27f1']]);
 await fs.writeFile(path.join(dir,'package.json'),JSON.stringify({dependencies:{phaser:'^4.2.0'}}));
 assert.equal((await inspect(dir)).status,'ambiguous');
});
